// Turns scripts/words.txt (one guessable word per line, from
// github.com/tabatkins/wordle-list) into src/lib/words.ts: every word sorted
// and run together in one string, so the server can binary-search it without
// building a 15k-entry Set on each request.
import { readFileSync, writeFileSync } from 'node:fs';

const words = [
  ...new Set(
    readFileSync(new URL('./words.txt', import.meta.url), 'utf8')
      .split(/\s+/)
      .map((w) => w.trim().toLowerCase())
      .filter((w) => /^[a-z]{5}$/.test(w)),
  ),
].sort();

writeFileSync(
  new URL('../src/lib/words.ts', import.meta.url),
  `// Generated by scripts/build-words.mjs. ${words.length} words, sorted, 5 letters each.\n` +
    `export const WORDS = '${words.join('')}';\n`,
);
console.log(`wrote ${words.length} words`);
